import assert from 'node:assert/strict';
import { assetById } from '../src/data/shops.ts';
import { createLife } from '../src/engine/create.ts';
import { postTransaction } from '../src/engine/journal.ts';
import { propertyQuote } from '../src/engine/property.ts';
import { relocationQuote } from '../src/engine/relocation.ts';
import { money } from '../src/i18n/en.ts';
import { acknowledgeEvents, saveSlot, startBrowser, url } from './browserTestSupport.mjs';

const id = 'world-browser-test';
const browser = await startBrowser();
try {
  const page = await browser.newPage({ viewport: { width: 320, height: 740 }, isMobile: true, hasTouch: true });
  const errors = [];
  page.on('pageerror', (error) => errors.push(error.message));
  const button = (name) => page.getByRole('button', { name, exact: true });
  const click = (name) => button(name).click();
  const heading = (name) => page.getByRole('heading', { name, exact: true });
  const read = async () => JSON.parse((await page.evaluate(saveSlot, { id })).payload);
  const dialog = (name) => page.getByRole('dialog', { name, exact: true });

  await page.goto(url);
  await button('New Life').waitFor();
  const life = createLife(42);
  life.character.age = 26;
  life.year += 26;
  postTransaction(life, 'Savings', 100000, 'other');
  const { firstName, lastName, city, age } = life.character;
  const destination = city === 'Bellmere' ? 'Northwick' : 'Bellmere';
  const original = { ...life, version: 8, world: undefined, character: { ...life.character, birthCity: undefined } };
  await page.evaluate(saveSlot, { id, entry: { id, name: `${firstName} ${lastName}`, city, age, year: life.year,
    completed: false, revision: 0, updatedAt: Date.now(), payload: JSON.stringify(original) } });
  await page.goto(new URL(`#play/${id}/journal`, url).href);
  await heading('Life Journal').waitFor();
  await click('World');
  await page.getByText('Economic regime', { exact: true }).waitFor();
  await click('Industry Report');
  await heading('Technology').waitFor();
  await heading('Healthcare').waitFor();
  await click('Back to World');
  await click('World News');
  await page.getByText('Fictional news from your Veyra simulation.', { exact: true }).waitFor();
  await page.getByText('No major developments this year.', { exact: true }).waitFor();
  await click('Back to World');
  await click('World History');
  assert.equal(await page.locator('.world-chart-bars span').count(), 1);
  await click('Back to World');
  await click('Compare Cities');
  await click(destination);
  await page.getByText('Housing market index', { exact: true }).waitFor();
  await click(`Move to ${destination}`);
  await dialog('Confirm Relocation').getByText('Moving cost', { exact: true }).waitFor();
  await click('Close Confirm Relocation');
  assert.equal((await read()).character.city, city);
  await click(`Move to ${destination}`);
  await click('Confirm Move');
  await dialog('A New City').waitFor();
  await acknowledgeEvents(page);
  const moved = await read();
  const migrationYear = moved.world.history[0];
  assert.equal(moved.version, 11);
  assert.equal(migrationYear.priceIndex, 10000);
  assert.equal(moved.character.birthCity, city);
  assert.equal(moved.character.city, destination);
  assert.equal(moved.property.residence, 'rent');
  assert.equal(moved.character.bank, life.character.bank - relocationQuote(moved, destination));
  await click('Back to Compare Cities');
  await click('Back to World');
  await click('Close World');
  await click('Age Up');
  await page.locator('.profile-identity p').filter({ hasText: 'Age 27 ·' }).waitFor();
  await acknowledgeEvents(page, true);
  await click('World');
  await click('World History');
  assert.equal(await page.locator('.world-chart-bars span').count(), 2);
  await page.reload();
  await heading('World History').waitFor();
  assert.equal(await page.locator('.world-chart-bars span').count(), 2);
  assert.deepEqual((await read()).world.history[0], migrationYear);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth === innerWidth), true);
  await page.setViewportSize({ width: 390, height: 844 });
  await click('Back to World');
  await click('Close World');
  await click('Assets');
  await click('Shopping');
  await click('Houses');
  await click('Cedar Starter House');
  const quote = propertyQuote(await read(), assetById.get('cedar-starter'));
  await button('Buy').getByText(money(quote.price), { exact: true }).waitFor();
  await click('Buy');
  await dialog('Purchase Complete').waitFor();
  await acknowledgeEvents(page);
  const bought = await read();
  assert.deepEqual(bought.property.owned[0].acquisition, quote);
  assert.equal(bought.property.owned[0].city, destination);
  assert.equal(bought.transactions.at(-1).amount, -quote.price);
  assert.equal(bought.character.bank, bought.transactions.reduce((sum, item) => sum + item.amount, 0));
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await page.context().setOffline(true);
  await page.reload();
  await heading('Cedar Starter House').waitFor();
  assert.ok(await button('Buy').isDisabled());
  await click('Back to Houses');
  await click('Back to Shopping');
  await click('Back to Assets');
  await click('Close Assets');
  await click('Age Up');
  await page.locator('.profile-identity p').filter({ hasText: 'Age 28 ·' }).waitFor();
  await acknowledgeEvents(page, true);
  assert.equal((await read()).world.history.length, 3);
  assert.deepEqual(errors, []);
  console.log('World smoke passed at 320px and 390px: V8 migration, reports, relocation, market quote, offline reload and Age Up.');
} finally {
  await browser.close();
}
